import { requireSkuAccess, readAssetJson, safeError } from "../_lib/sku_api.js";

function isShopifyQlReport(report) {
  // dataQuality belongs to each reporting period (FY2025, YTD2026 and MONTH),
  // not to the report root. Check the nested period objects so newly generated
  // ShopifyQL reports are not incorrectly rejected as legacy reports.
  const periodReports = Object.values(report?.periods || {});
  const hasShopifyQlSalesSource = periodReports.some((periodReport) =>
    String(periodReport?.dataQuality?.salesSource || "").includes("ShopifyQL FROM sales")
  );

  return report?.source?.primary === "ShopifyQL sales analytics"
    && hasShopifyQlSalesSource;
}

function outdatedReportResponse() {
  return Response.json({
    error: "This report was generated by the previous order-based calculation and does not contain the complete ShopifyQL sales bridge. Run GitHub Actions → Monthly SKU Intelligence Report → Run workflow to rebuild the data before using these figures.",
    code: "shopifyql_refresh_required"
  }, {
    status: 409,
    headers: { "cache-control": "private, no-store" }
  });
}

export async function onRequestGet(context) {
  try {
    await requireSkuAccess(context);
    const url = new URL(context.request.url);
    const store = url.searchParams.get("store") || "equestrian";
    const month = url.searchParams.get("month");
    if (!["equestrian", "cavali"].includes(store)) {
      return Response.json({ error: "Invalid store" }, { status: 400 });
    }

    const latest = await readAssetJson(context, "/data/latest-report.json");
    if (!latest) {
      return Response.json({ error: "No published report data yet." }, { status: 404 });
    }

    const selectedMonth = month || latest.month;
    if (!/^\d{4}-\d{2}$/.test(selectedMonth)) {
      return Response.json({ error: "Invalid month" }, { status: 400 });
    }

    if (selectedMonth === latest.month && latest.stores?.[store]?.report) {
      const report = latest.stores[store].report;
      if (!isShopifyQlReport(report)) return outdatedReportResponse();
      return Response.json(report, { headers: { "cache-control": "private, no-store" } });
    }

    const archive = await readAssetJson(
      context,
      `/data/archive/${store}/${selectedMonth.slice(0, 4)}/${selectedMonth}.json`
    );
    if (!archive?.report) {
      return Response.json({ error: "No archive found for the selected month." }, { status: 404 });
    }
    if (!isShopifyQlReport(archive.report)) return outdatedReportResponse();
    return Response.json(archive.report, { headers: { "cache-control": "private, no-store" } });
  } catch (error) {
    return safeError(error);
  }
}
